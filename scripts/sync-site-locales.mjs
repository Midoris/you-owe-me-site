// Refresh crawlable counterpart annotations and links from reviewed locale routes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { siteLocales, localeOrigin, completedCounterparts, localeAssetVersion, sharedAssetVersions } from "../content/site-locales.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const esc = value => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;");
const regexEsc = value => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const sections = ["solutions", "features", "reviews", "tools", "compare", "blog"];
const frenchRepaymentRoute = "/fr/blog/comment-reclamer-son-argent-poliment/";
const frenchRepaymentSource = "/blog/how-to-remind-someone-they-owe-you-money-politely/";
const spanishDisclosureRoutes = new Set([
  "/es/blog/como-pedir-dinero-prestado-a-un-amigo/",
  "/es/blog/como-pedir-que-te-devuelvan-dinero/",
]);

export function renderLocaleHtml(html, englishRoute, lang, locales = siteLocales) {
  const locale = locales.find(locale => locale.code === lang);
  const counterparts = completedCounterparts(englishRoute, locales);
  const route = counterparts.find(counterpart => counterpart.code === lang)?.route;
  if (!locale || !route) throw new Error(`Unreviewed locale counterpart: ${lang} ${englishRoute}`);
  html = html.replace(/\s*<!-- locale-alternates:start -->[\s\S]*?<!-- locale-alternates:end -->/g, "");
  const alternates = `\n    <!-- locale-alternates:start -->\n${[...counterparts, { code: "x-default", route: englishRoute }].map(({ code, route }) => `    <link rel="alternate" hreflang="${code}" href="${localeOrigin}${route}" />`).join("\n")}\n    <!-- locale-alternates:end -->`;
  html = html.replace(/<link rel="canonical"[^>]*>/, match => match + alternates);
  html = html.replace(/\s*<!-- locale-switch:start -->[\s\S]*?<!-- locale-switch:end -->/g, "");
  const switchLinks = counterparts.map(({ code, route }) => `<a href="${route}" lang="${code}"${code === "ar" ? ' dir="rtl"' : lang === "ar" ? ' dir="ltr"' : ""} hreflang="${code}"${lang === code ? ' aria-current="page"' : ""}>${locales.find(locale => locale.code === code).label}</a>`).join('<span aria-hidden="true"> · </span>');
  const switcher = `\n        <!-- locale-switch:start -->\n        <li class="site-language-switch" aria-label="${esc(locale.shared.languageLabel)}">${switchLinks}</li>\n        <!-- locale-switch:end -->`;
  html = html.replace(/(<div id="copyright">\s*<ul>)/, "$1" + switcher);
  // Shared correctness fixes also need fresh URLs in the English sources.
  // Preserve authored relative/absolute paths; only the cache query is owned.
  const assets = lang === "en" ? Object.keys(sharedAssetVersions) : locale.versionedAssets;
  for (const asset of assets) {
    const relative = path.posix.relative(englishRoute, asset);
    const references = lang === "en" ? [asset, relative, `./${relative}`] : [asset];
    for (const reference of references) {
      html = html.replace(new RegExp(`((?:src|href)=")${regexEsc(reference)}(?:\\?[^\"]*)?(\")`, "g"), `$1${reference}?v=${localeAssetVersion(locale, asset)}$2`);
    }
  }
  if (lang === "en") return html;

  const completed = locale.pages.filter(page => page.complete);
  const localized = url => completed.find(page => page.en === url)?.[lang] || url;
  // The English Best Next Step builder never owns translated modules.
  html = html.replaceAll("<!-- best-next-step:start -->", "<!-- localized-next-step:start -->")
    .replaceAll("<!-- best-next-step:end -->", "<!-- localized-next-step:end -->")
    .replaceAll("<!-- Generated by scripts/build-best-next-steps.mjs. Edit content/content-registry.mjs instead. -->", `<!-- ${locale.nextStepComment} -->`);
  const home = localized("/");
  const navItems = `<li${englishRoute === "/" ? ' class="active"' : ""}><a href="${home}">${lang === "ar" ? '<bdi dir="ltr">You Owe Me</bdi>' : "You Owe Me"}${home === "/" ? ` (${locale.shared.englishFallback})` : ""}</a></li>` + sections.map(section => `<li${englishRoute.startsWith(`/${section}/`) ? ' class="active"' : ""}><a href="/${section}/">${locale.shared.navigation[section]} (${locale.shared.englishFallback})</a></li>`).join("");
  html = html.replace(/(<nav id="nav">\s*<ul class="links">)[\s\S]*?(<\/ul>\s*<\/nav>)/, `$1\n          ${navItems}\n        $2`);
  html = html.replace(/(<div id="copyright">)[\s\S]*?(<\/ul>)/, footer => {
    for (const [href, label] of [...sections.map(section => [`/${section}/`, locale.shared.navigation[section]]), ...Object.entries(locale.shared.footer)]) {
      footer = footer.replace(new RegExp(`(<a href="${regexEsc(href)}">)[\\s\\S]*?(<\\/a>)`, "g"), `$1${label} (${locale.shared.englishFallback})$2`);
    }
    return footer;
  });
  // Only the reviewed French repayment counterpart receives this exact native label.
  if (lang === "fr" && completed.some(page => page.en === frenchRepaymentSource)) {
    html = html.replace(new RegExp(`(<a\\b[^>]*href=")${regexEsc(frenchRepaymentSource)}("[^>]*>)[\\s\\S]*?(<\\/a>)`, "g"), (original, start, end, close) => /\b(?:lang|hreflang)=/.test(start + end) ? original : `${start}${frenchRepaymentRoute}${end}${/\blt-cardCta\b/.test(start + end) ? "Messages pour demander un remboursement" : "messages pour demander un remboursement"}${close}`);
  }
  for (const target of completed) {
    html = html.replace(new RegExp(`(<a\\b[^>]*href=")${regexEsc(target.en)}(#[^"]*)?("[^>]*>)([\\s\\S]*?)(<\\/a>)`, "g"), (original, start, hash, end, label, close) => /\blang="en"/.test(start + end) ? original : `${start}${target[lang]}${hash || ""}${end}${label.replace(new RegExp(`\\s*\\(${regexEsc(locale.shared.englishFallback)}\\)`, "g"), "").replace(/<span class="site-locale-fallback">\s*<\/span>/g, "")}${close}`);
  }
  const nav = completed.map(target => `<a href="${target[lang]}"${target[lang] === route ? ' aria-current="page"' : ""}>${lang === "ar" ? esc(target.title).replaceAll("You Owe Me", '<bdi dir="ltr">You Owe Me</bdi>') : esc(target.title)}</a>`).join("\n              ");
  const marker = locale.sectionMarker;
  html = html.replace(new RegExp(`\\s*<!-- ${marker}-section:start -->[\\s\\S]*?<!-- ${marker}-section:end -->`, "g"), "");
  const sectionNav = `<nav class="${locale.sectionClass}" aria-label="${esc(locale.shared.sectionLabel)}">${nav}</nav>`;
  const sectionContent = lang === "ar" && route === "/ar/blog/how-to-remind-someone-they-owe-you-money-politely/"
    ? `<details class="site-arabic-disclosure"><summary>صفحات بالعربية</summary>${sectionNav}</details>`
    : lang === "de" && ["/de/blog/geld-freundlich-zurueckfordern/", "/de/blog/freunde-um-geld-bitten/"].includes(route)
    ? `<details class="site-german-disclosure"><summary>Seiten auf Deutsch</summary>${sectionNav}</details>`
    : lang === "es" && spanishDisclosureRoutes.has(route)
    ? `<details class="site-spanish-disclosure"><summary>Más guías en español</summary>${sectionNav}</details>`
    : lang === "fr" && route === frenchRepaymentRoute
      ? `<details class="site-french-disclosure"><summary>Pages en français</summary>${sectionNav}</details>`
      : sectionNav;
  html = html.replace(/(<article\b[^>]*>)/, `$1\n          <!-- ${marker}-section:start -->\n          ${sectionContent}\n          <!-- ${marker}-section:end -->`);
  return html;
}

export function renderLocaleDiscovery(discovery, locales = siteLocales) {
  const translations = locales.filter(locale => locale.code !== "en");
  for (const locale of translations) {
    const marker = locale.sectionMarker;
    discovery = discovery.replace(new RegExp(`\\n<!-- ${marker}-pages:start -->[\\s\\S]*?<!-- ${marker}-pages:end -->\\n?`, "g"), "\n");
  }
  for (const locale of translations) {
    const marker = locale.sectionMarker;
    const completed = locale.pages.filter(page => page.complete);
    if (completed.length) discovery = discovery.trimEnd() + `\n\n<!-- ${marker}-pages:start -->\n## ${locale.shared.sectionLabel}\n\n${locale.shared.discoveryDescription}\n\n${completed.map(page => `- [${page.title}](${localeOrigin}${page[locale.code]})${page.discoveryDescription ? ` — ${page.discoveryDescription}` : ""}`).join("\n")}\n<!-- ${marker}-pages:end -->\n`;
  }
  return discovery;
}

export function syncSiteLocales(rootDir = root, locales = siteLocales) {
  const englishRoutes = new Set(locales.flatMap(locale => locale.pages.filter(page => page.complete).map(page => page.en)));
  // Check the entire batch before writing anything, so a mistaken complete flag
  // cannot leave half of a reciprocal group updated.
  const jobs = [...englishRoutes].flatMap(englishRoute => completedCounterparts(englishRoute, locales).map(({ code, route }) => ({ englishRoute, code, route, file: path.join(rootDir, route, "index.html") })));
  for (const { file, route } of jobs) if (!fs.existsSync(file)) throw new Error(`Reviewed counterpart missing: ${route}`);
  for (const { file, englishRoute, code } of jobs) fs.writeFileSync(file, renderLocaleHtml(fs.readFileSync(file, "utf8"), englishRoute, code, locales));
  const discoveryFile = path.join(rootDir, "llms.txt");
  fs.writeFileSync(discoveryFile, renderLocaleDiscovery(fs.readFileSync(discoveryFile, "utf8"), locales));
  return jobs.length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) console.log(`Updated ${syncSiteLocales()} reviewed language pages.`);
